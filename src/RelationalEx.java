
public class RelationalEx {

	public static void main(String[] args) {
		
		int no1 = 10, no2 = 5, no3 = 10;
		
		System.out.println( (no1 == no2) );  // false
		
		System.out.println( (no1 == no3) );  // true
		
		System.out.println( (no1 != no2) );  // true
		
		System.out.println( (no1 != no3) );  // false
		
		System.out.println( (no1 > no2) ); // true
		
		System.out.println( (no1 >= no3) ); // true
		
		System.out.println( (no1 < no2) ); // false
		
		System.out.println( (no1 <= no3) );  // true
		
		
		

	}

}
